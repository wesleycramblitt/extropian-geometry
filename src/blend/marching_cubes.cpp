static uint64_t pack_edge_key(int ix, int iy, int iz, int edge)
{
    return (static_cast<uint64_t>(static_cast<uint16_t>(ix)))
         | (static_cast<uint64_t>(static_cast<uint16_t>(iy)) << 16)
         | (static_cast<uint64_t>(static_cast<uint16_t>(iz)) << 32)
         | (static_cast<uint64_t>(edge) << 48);
}

/// Evaluate SDF at a world-space point by indexing into the grid.
/// Uses trilinear interpolation for sub-cell positions.
static float grid_value_at(const SdfGrid& grid, const math::Vec3f& p)
{
    float fx = (p.x - grid.origin.x) / grid.cellSize;
    float fy = (p.y - grid.origin.y) / grid.cellSize;
    float fz = (p.z - grid.origin.z) / grid.cellSize;
    int ix = static_cast<int>(std::floor(fx));
    int iy = static_cast<int>(std::floor(fy));
    int iz = static_cast<int>(std::floor(fz));

    // Clamp to grid bounds
    ix = std::clamp(ix, 0, grid.nx - 2);
    iy = std::clamp(iy, 0, grid.ny - 2);
    iz = std::clamp(iz, 0, grid.nz - 2);

    float tx = fx - static_cast<float>(ix);
    float ty = fy - static_cast<float>(iy);
    float tz = fz - static_cast<float>(iz);

    float c000 = grid.at(ix,     iy,     iz);
    float c100 = grid.at(ix + 1, iy,     iz);
    float c010 = grid.at(ix,     iy + 1, iz);
    float c110 = grid.at(ix + 1, iy + 1, iz);
    float c001 = grid.at(ix,     iy,     iz + 1);
    float c101 = grid.at(ix + 1, iy,     iz + 1);
    float c011 = grid.at(ix,     iy + 1, iz + 1);
    float c111 = grid.at(ix + 1, iy + 1, iz + 1);

    float c00 = c000 * (1 - tx) + c100 * tx;
    float c10 = c010 * (1 - tx) + c110 * tx;
    float c01 = c001 * (1 - tx) + c101 * tx;
    float c11 = c011 * (1 - tx) + c111 * tx;

    float c0 = c00 * (1 - ty) + c10 * ty;
    float c1 = c01 * (1 - ty) + c11 * ty;

    return c0 * (1 - tz) + c1 * tz;
}

/// Compute normal from grid values via central differences.
static math::Vec3f grid_normal(const SdfGrid& grid, const math::Vec3f& p)
{
    float eps = grid.cellSize * 0.5f;
    float dx = grid_value_at(grid, {p.x + eps, p.y, p.z})
             - grid_value_at(grid, {p.x - eps, p.y, p.z});
    float dy = grid_value_at(grid, {p.x, p.y + eps, p.z})
             - grid_value_at(grid, {p.x, p.y - eps, p.z});
    float dz = grid_value_at(grid, {p.x, p.y, p.z + eps})
             - grid_value_at(grid, {p.x, p.y, p.z - eps});
    math::Vec3f n{dx, dy, dz};
    float len = n.length();
    if (len > 1e-8f) return n / len;
    return {0, 1, 0};
}

MeshData extract_isosurface(const SdfGrid& grid, bool generateNormals)
{
    MeshBuilder builder;
    std::unordered_map<uint64_t, uint32_t> edgeToVertex;

    const float iso = 0.0f;
    const int mx = grid.nx - 1;
    const int my = grid.ny - 1;
    const int mz = grid.nz - 1;

    // Rough reserve estimate
    size_t estTris = static_cast<size_t>(mx) * my * mz / 3;
    builder.reserve(estTris, estTris * 3);

    for (int iz = 0; iz < mz; ++iz)
    {
        for (int iy = 0; iy < my; ++iy)
        {
            for (int ix = 0; ix < mx; ++ix)
            {
                // Gather corner values and positions
                float cornerVal[8];
                math::Vec3f cornerPos[8];
                for (int c = 0; c < 8; ++c)
                {
                    int cx = ix + static_cast<int>(kCornerOffsets[c].x);
                    int cy = iy + static_cast<int>(kCornerOffsets[c].y);
                    int cz = iz + static_cast<int>(kCornerOffsets[c].z);
                    cornerVal[c] = grid.at(cx, cy, cz);
                    cornerPos[c] = {
                        grid.origin.x + cx * grid.cellSize,
                        grid.origin.y + cy * grid.cellSize,
                        grid.origin.z + cz * grid.cellSize
                    };
                }

                // Case index
                int caseIdx = 0;
                for (int c = 0; c < 8; ++c)
                    if (cornerVal[c] < iso) caseIdx |= (1 << c);

                int edgeMask = kEdgeTable[caseIdx];
                if (edgeMask == 0) continue;

                // Interpolate edge vertices
                math::Vec3f edgeVert[12];
                for (int e = 0; e < 12; ++e)
                {
                    if (!(edgeMask & (1 << e))) continue;
                    int c0 = kEdgePair[e][0];
                    int c1 = kEdgePair[e][1];
                    float v0 = cornerVal[c0];
                    float v1 = cornerVal[c1];
                    float t = (iso - v0) / (v1 - v0);
                    t = std::clamp(t, 0.0f, 1.0f);
                    edgeVert[e] = {
                        cornerPos[c0].x + t * (cornerPos[c1].x - cornerPos[c0].x),
                        cornerPos[c0].y + t * (cornerPos[c1].y - cornerPos[c0].y),
                        cornerPos[c0].z + t * (cornerPos[c1].z - cornerPos[c0].z)
                    };
                }

                // Emit triangles
                const int* tri = kTriTable[caseIdx];
                for (int t = 0; tri[t] != -1 && tri[t + 1] != -1 && tri[t + 2] != -1; t += 3)
                {
                    uint32_t vidx[3];
                    bool valid = true;
                    for (int v = 0; v < 3; ++v)
                    {
                        int edge = tri[t + v];
                        if (edge < 0 || edge >= 12) { valid = false; break; }
                        if (!(edgeMask & (1 << edge))) { valid = false; break; }
                        uint64_t key = pack_edge_key(ix, iy, iz, edge);
                        auto it = edgeToVertex.find(key);
                        if (it != edgeToVertex.end())
                        {
                            vidx[v] = it->second;
                        }
                        else
                        {
                            Vertex vtx;
                            vtx.position = edgeVert[edge];
                            vtx.normal = generateNormals ? grid_normal(grid, vtx.position) : math::Vec3f{0, 1, 0};
                            vtx.uv = {0, 0, 0};
                            uint32_t idx = builder.add_vertex(vtx);
                            edgeToVertex[key] = idx;
                            vidx[v] = idx;
                        }
                    }
                    if (valid)
                        builder.add_triangle(vidx[0], vidx[1], vidx[2]);
                }
            }
        }
    }

    return builder.build();
}

